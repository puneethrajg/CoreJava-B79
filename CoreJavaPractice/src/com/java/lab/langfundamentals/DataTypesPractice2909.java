package com.java.lab.langfundamentals;

//	WAP to demonstrate the use of all 8 primitive data types in Java
public class DataTypesPractice2909 {
	
	public static void main(String[] args) {
		
		byte age = 22;
		short numberOfStudents = 10000;
		int annualSalary = 5;
		float percentage = 75.6f;
		double bankBalance = 9000.0;
		char grade = 'A';
		boolean isJavaLearner = true;
		long mobileNo = 12345678912L;
		
		System.out.println("Age : "+age);
		System.out.println("No of Students in College : "+numberOfStudents);
		System.out.println("Annual Salary : "+annualSalary);
		System.out.println("Percentage : "+percentage);
		System.out.println("Bank Balance : "+bankBalance);
		System.out.println("College Grade : "+grade);
		System.out.println("Is Java Learner : "+isJavaLearner);
		System.out.println("Mobile No : "+mobileNo);
		
		
	}

}
